const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:4175/site/';
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[],requests=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>requests.push(r.url()));
    page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
    await page.goto(base);
    await page.waitForSelector('.model-card');
    assert.equal(await page.locator('.model-card').count(),3);
    assert.equal(requests.filter(x=>/\/data\/(?!models\.json)[^/]+\.json/.test(x)).length,0,'Home loads only model summaries');
    await page.screenshot({path:'tmp/multi-home-desktop.png',fullPage:true});
    await page.locator('.model-card[href="#/982"]').click();
    await page.waitForSelector('#search');
    assert.ok((await page.locator('.library-title').innerText()).includes('982'));
    assert.ok(!(await page.locator('.library-title').innerText()).includes('981'));
    await page.locator('#search').fill('Engine');
    await page.waitForFunction(()=>document.querySelector('.result-heading')?.textContent.includes('Engine'));
    await page.locator('.document-row').first().click();
    await page.waitForSelector('.pdf-status[hidden]',{state:'attached'});
    assert.ok(page.url().includes('/982/doc/982-0001'));
    assert.ok(requests.some(x=>x.includes('/docs/982/982-0001.pdf')));
    await page.locator('#next-page').click();
    await page.waitForFunction(()=>document.querySelector('#page-number')?.value==='2');
    await page.reload();
    await page.waitForSelector('.pdf-status[hidden]',{state:'attached'});
    assert.equal(await page.locator('#page-number').inputValue(),'2');
    await page.locator('.reader-heading .back-link').click();
    await page.waitForSelector('#search');
    assert.equal(await page.locator('#search').inputValue(),'Engine');
    await page.goto(base+'#/911-992/doc/911-992-0001?page=1');
    await page.waitForSelector('.pdf-status[hidden]',{state:'attached'});
    assert.ok((await page.locator('.reader-heading').innerText()).includes('911-992'));
    assert.ok((await page.locator('.reader-heading .back-link').getAttribute('href')).startsWith('#/911-992'));
    await page.locator('.brand').click();
    await page.waitForSelector('.resume');
    assert.ok((await page.locator('.resume').getAttribute('href')).includes('911-992'));
    await page.goto(base+'#/982/doc/981-0002');
    await page.waitForSelector('.empty-state');
    assert.ok((await page.locator('.empty-state').innerText()).includes('没有找到'));
    // Slow catalog responses must not replace a newer route.
    await page.reload();
    await page.waitForSelector('.empty-state');
    await page.route('**/data/911-992.json',async r=>{await new Promise(resolve=>setTimeout(resolve,250));await r.continue();});
    await page.goto(base+'#/911-992');
    await page.goto(base+'#/');
    await page.waitForSelector('.model-card');
    await page.waitForTimeout(400);
    assert.equal(await page.locator('.model-card').count(),3);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'tmp/multi-home-mobile.png',fullPage:true});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.locator('.model-card[href="#/911-992"]').click();
    await page.waitForSelector('#search');
    await page.screenshot({path:'tmp/multi-library-mobile.png',fullPage:false});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    assert.deepEqual(errors,[]);
    console.log('PASS: automatic cards, lazy catalogs, separate model search/PDFs, deep links, reload, resume, return filters, race handling, mobile layout.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
